import { Finding, LetterGrade, ScanResult, SeverityCounts } from '@/lib/types/scanner';

/**
 * Calculates overall numeric score (0-100), letter grade (A-F),
 * and severity count breakdown based on findings.
 */
export function calculateScoreAndGrade(findings: Finding[]): {
  overallScore: number;
  grade: LetterGrade;
  severityCounts: SeverityCounts;
} {
  const severityCounts: SeverityCounts = {
    critical: 0,
    high: 0,
    medium: 0,
    low: 0,
    info: 0,
  };

  let criticalDeduction = 0;
  let highDeduction = 0;
  let mediumDeduction = 0;
  let lowDeduction = 0;

  for (const f of findings) {
    if (f.severity === 'critical') {
      severityCounts.critical++;
      criticalDeduction += f.deduction;
    } else if (f.severity === 'high') {
      severityCounts.high++;
      highDeduction += f.deduction;
    } else if (f.severity === 'medium') {
      severityCounts.medium++;
      mediumDeduction += f.deduction;
    } else if (f.severity === 'low') {
      severityCounts.low++;
      lowDeduction += f.deduction;
    } else if (f.severity === 'info') {
      severityCounts.info++;
    }
  }

  // Apply maximum category caps to ensure balanced penalties
  const cappedCritical = Math.min(80, criticalDeduction);
  const cappedHigh = Math.min(50, highDeduction);
  const cappedMedium = Math.min(36, mediumDeduction);
  const cappedLow = Math.min(15, lowDeduction);

  const totalDeductions = cappedCritical + cappedHigh + cappedMedium + cappedLow;
  const overallScore = Math.max(0, 100 - totalDeductions);

  let grade: LetterGrade = 'F';
  if (overallScore >= 90) grade = 'A';
  else if (overallScore >= 80) grade = 'B';
  else if (overallScore >= 70) grade = 'C';
  else if (overallScore >= 60) grade = 'D';
  else grade = 'F';

  return {
    overallScore,
    grade,
    severityCounts,
  };
}

/**
 * Generates an exportable, professional GitHub-Flavored Markdown report.
 */
export function generateMarkdownReport(result: ScanResult): string {
  const { targetUrl, scannedAt, overallScore, grade, severityCounts, findings, frameworkDetected } = result;

  const dateStr = new Date(scannedAt).toUTCString();

  let md = `# 🛡️ ShipSafe Security Hygiene Report\n\n`;
  md += `**Target URL:** \`${targetUrl}\`  \n`;
  md += `**Audit Date:** ${dateStr}  \n`;
  md += `**Framework Detected:** ${frameworkDetected || 'Generic Web App'}  \n`;
  md += `**Overall Grade:** **${grade}** (${overallScore}/100)  \n\n`;

  md += `## 📊 Executive Summary\n\n`;
  md += `| Severity | Count | Impact |\n`;
  md += `| :--- | :--- | :--- |\n`;
  md += `| 🔴 **Critical** | ${severityCounts.critical} | Database bypass, live credentials, or raw .env exposure |\n`;
  md += `| 🟠 **High** | ${severityCounts.high} | Exposed source maps, permissive CORS with credentials |\n`;
  md += `| 🟡 **Medium** | ${severityCounts.medium} | Missing CSP, HSTS, or session cookie protections |\n`;
  md += `| 🔵 **Low** | ${severityCounts.low} | MIME sniffing, referrer leaks, verbose server banners |\n`;
  md += `| ⚪ **Info** | ${severityCounts.info} | Public client keys & architectural checklists |\n\n`;

  if (findings.length === 0) {
    md += `> ✅ **No security hygiene gaps identified!** The target site follows modern defense-in-depth security best practices.\n\n`;
    return md;
  }

  md += `## 🔍 Detailed Findings & Remediation\n\n`;

  findings.forEach((finding, index) => {
    const severityIcon = 
      finding.severity === 'critical' ? '🔴' :
      finding.severity === 'high' ? '🟠' :
      finding.severity === 'medium' ? '🟡' :
      finding.severity === 'low' ? '🔵' : '⚪';

    md += `### ${index + 1}. ${severityIcon} [${finding.severity.toUpperCase()}] ${finding.title}\n\n`;
    md += `* **Category:** \`${finding.category}\`  \n`;
    if (finding.owaspMapping) {
      md += `* **Standard Mapping:** ${finding.owaspMapping}  \n`;
    }
    if (finding.assetUrl) {
      md += `* **Asset Location:** \`${finding.assetUrl}\`  \n`;
    }
    if (finding.maskedEvidence) {
      md += `* **Evidence (Redacted):** \`${finding.maskedEvidence}\`  \n`;
    }
    md += `* **Score Deduction:** -${finding.deduction} pts  \n\n`;

    md += `**Impact:**  \n${finding.impact}\n\n`;
    md += `**Recommended Fix:**  \n${finding.remediationSummary}\n\n`;

    md += `#### 🤖 AI Fix Prompt (Copy & Paste to Cursor / Claude / ChatGPT)\n`;
    md += `\`\`\`markdown\n${finding.fixPrompt}\n\`\`\`\n\n`;
    md += `---\n\n`;
  });

  md += `\n*Generated by **ShipSafe** — The Passive Security Hygiene Auditor for Modern Web Apps.*\n`;
  return md;
}
